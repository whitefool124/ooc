"""Reproducible CC0 cinematic edit; fixed-camera16-second spell, no destruction."""
from pathlib import Path
import subprocess,hashlib,json,wave
import numpy as np

root=Path(__file__).resolve().parents[3]
folder=Path(__file__).resolve().parent
output=root/'UnityProject/Assets/Resources/Audio/OCC/SkyFurnace'
output.mkdir(parents=True,exist_ok=True)
sr=48000; duration=16;count=sr*duration
t=np.arange(count)/sr
inputs=[];events=[]
def read(path,filters=None):
    path=Path(path)
    inputs.append({'path':path.relative_to(root).as_posix(),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
    command=['ffmpeg','-v','error','-i',str(path)]
    if filters:command+=['-af',filters]
    data=subprocess.check_output(command+['-f','f32le','-ar',str(sr),'-ac','2','pipe:1'])
    return np.frombuffer(data,dtype='<f4').reshape(-1,2).copy()
def save(path,data):
    with wave.open(str(path),'wb') as w:
        w.setnchannels(2);w.setsampwidth(2);w.setframerate(sr);w.writeframes((np.clip(data,-.98,.98)*32767).astype('<i2').tobytes())
def warp(x,pitch):
    positions=np.arange(0,len(x)-1,pitch);indices=np.arange(len(x))
    return np.stack([np.interp(positions,indices,x[:,c]) for c in range(2)],axis=1)
def mix(x,at,gain,pan=0,pitch=1):
    x=warp(x,pitch) if pitch!=1 else x.copy()
    start=int(at*sr);length=min(len(x),count-start)
    if length<=0:return
    x=x[:length]*gain
    x[:,0]*=min(1,1-pan);x[:,1]*=min(1,1+pan)
    fade=min(length//3,int(.025*sr));x[:fade]*=np.linspace(0,1,fade)[:,None];x[-fade:]*=np.linspace(1,0,fade)[:,None]
    sfx[start:start+length]+=x
    events.append({'at':at,'gain':gain,'pan':pan,'pitch':pitch,'duration':length/sr})

music_raw=read(folder/'unexplored_short_TAD_CC0.mp3','atrim=end=24,atempo=1.5')
# Source has its final cadence near23s followed by a long silent tail. Keep the
# whole musical phrase with a modest time edit, never looping under the finale.
music=np.zeros((count,2),dtype=float);music[:min(count,len(music_raw))]=music_raw[:count]
envelope=np.interp(t,[0,1,3,6.5,7,7.4,8.3,10,12,14.5,16],[0,.18,.29,.37,.10,.08,.18,.26,.20,.11,0])
music*=envelope[:,None]
sfx=np.zeros_like(music)
free=root/'UnityProject/Assets/Resources/Audio/OCC/SFX/FreeProcessed'
charge=read(free/'magical_1.wav');lock=read(free/'lock_01.wav');fire=read(free/'spell_fire_02.wav');hit=read(free/'impact_hit.wav')
boom=read(folder/'muffled_explosion_NenadSimic_CC0.wav')
wind=read(root/'UnityProject/Assets/Resources/Audio/OCC/Ambience/wind.wav')
mix(charge,0,.8,0,.8);mix(charge,1.2,.65,-.15,.65)
for i in range(3):mix(lock,3.1+i*.25,.32,(-1 if i%2 else 1)*.18,.78+i*.04)
# Original low-frequency/rising engineering layer complements licensed effects.
q=np.arange(int(5.6*sr))/sr
riser=np.sin(2*np.pi*(50*q+12*q*q))*.038+np.sin(2*np.pi*(160*q+30*q*q))*.022
riser*=np.clip(q/.5,0,1)*np.clip((5.6-q)/.3,0,1)
mix(np.column_stack((riser,riser)),1.2,1)
mix(fire,7,.8,0,.8);mix(hit,7.4,.75,0,.7);mix(boom,7.4,.60,0,.8)
q=np.arange(int(2.4*sr))/sr
body=np.sin(2*np.pi*(49*q-3*q*q))*np.exp(-q*2.8)*.19
mix(np.column_stack((body,body)),7.4,1)
mix(wind[:int(7*sr)],8.8,.12)
# Two short reflection taps retain an audible spacious decay without a constant roar.
dry=sfx.copy()
for delay,gain in [(.13,.14),(.31,.08)]:
    shift=int(delay*sr);sfx[shift:]+=dry[:-shift,::-1]*gain
sfx*=np.interp(t,[0,.04,14,16],[0,1,1,0])[:,None]
combined=music+sfx
gain=min(1,.90/max(float(np.abs(combined).max()),1e-9));music*=gain;sfx*=gain
save(output/'music_16s.wav',music);save(output/'sfx_16s.wav',sfx);save(folder/'sky_furnace_audition_16s.wav',music+sfx)
report={'schema':'occ-cinematic-audio-v1','duration':duration,'sample_rate':sr,'channels':2,'music_author':'TAD','music_source':'https://opengameart.org/content/unexplored-short-ver-orchestra-music',
 'explosion_author':'NenadSimic','explosion_source':'https://opengameart.org/content/muffled-distant-explosion','new_sources_license':'CC0-1.0','existing_sources_credits':'ArtSource/Audio/AUDIO_CREDITS.md',
 'original_synthesis':'phase-continuous engineering riser and bass body, generated by this script without external samples','inputs':inputs,'events':events,
 'mix_peak':float(np.abs(music+sfx).max()),'music_rms':float(np.sqrt(np.mean(music**2))),'sfx_rms':float(np.sqrt(np.mean(sfx**2))),
 'outputs':[{'path':p.relative_to(root).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in [output/'music_16s.wav',output/'sfx_16s.wav',folder/'sky_furnace_audition_16s.wav']],
 'human_audition':'PENDING','runtime_sync':'PENDING'}
(folder/'processing.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({k:report[k] for k in ['duration','mix_peak','music_rms','sfx_rms']}))
